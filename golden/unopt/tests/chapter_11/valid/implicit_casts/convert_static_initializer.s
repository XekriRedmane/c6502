   LDA   j+6
   BNE   .cmp_true@3
   LDA   j+5
   BNE   .cmp_true@3
   LDA   j+4
   BNE   .cmp_true@3
   LDA   j+3
   BNE   .cmp_true@3
   LDA   j+2
