"""Writes cpp/src/pcpp_evaluator_tables.h, the tables of the LALR parser
that pcpp 1.30's `#if` evaluator runs (pcpp/evaluator.py), for the C++
port of the preprocessor (docs/cpp_port.md, "The plan for the
preprocessor").

pcpp builds the parser with PLY's yacc from the grammar and precedence
in evaluator.py, so the tables are read from the live `LRParser` that
preprocessor.py's `CompilePreprocessor` uses: its actions, its gotos,
its productions with the name of each one's `p_` function, and its
defaulted states. The header also holds the ranges of the code points
that Python's `str.isprintable` rejects, which the evaluator's messages
escape in `repr`, from the Unicode database of the Python that runs
this script.

    uv run python tools/pcpp_evaluator_tables.py

tests/test_pcpp_evaluator_tables.py fails until the checked-in header
matches what this writes.
"""

from __future__ import annotations

import os
import sys
import unicodedata

_ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
_HEADER = os.path.join(_ROOT, "cpp", "src", "pcpp_evaluator_tables.h")

# The value of an empty cell of the action and goto tables.
_NONE = 32767


def _parser():
    if _ROOT not in sys.path:
        sys.path.insert(0, _ROOT)
    import preprocessor
    cp = preprocessor.CompilePreprocessor(preprocessor.parse_args([]))
    # `CompilePreprocessor.evaluator` is preprocessor.py's
    # `_NumberEvaluator`, which wraps pcpp's `Evaluator`.
    return cp.evaluator.evaluator.parser


def _non_printable_ranges() -> list[tuple[int, int]]:
    out: list[tuple[int, int]] = []
    for c in range(0x110000):
        if not chr(c).isprintable():
            if out and out[-1][1] == c - 1:
                out[-1] = (out[-1][0], c)
            else:
                out.append((c, c))
    return out


def generate() -> str:
    """Returns the text of the header."""
    p = _parser()
    terminals = sorted({t for acts in p.action.values() for t in acts}
                       | {"$end", "error"})
    nonterminals = sorted({n for g in p.goto.values() for n in g})
    states = len(p.action)
    if sorted(p.action) != list(range(states)):
        raise AssertionError("the parser's states aren't numbered 0..n-1")
    lines = [
        "// Generated by tools/pcpp_evaluator_tables.py from the LALR parser",
        "// that PLY's yacc builds for pcpp 1.30's `#if` evaluator",
        "// (pcpp/evaluator.py), and from Python's `str.isprintable`. Don't",
        "// edit it by hand.",
        "#pragma once",
        "",
        "#include <cstdint>",
        "",
        "namespace c6502::pcpp::evaluator_tables {",
        "",
        "// The value of a cell that holds no action or goto.",
        f"constexpr std::int16_t kNone = {_NONE};",
        "",
        "// The terminals, by the names of the grammar's tokens, sorted.",
        f"constexpr int kTerminalCount = {len(terminals)};",
        "constexpr const char* kTerminals[kTerminalCount] = {",
    ]
    lines += [f'    "{t}",' for t in terminals]
    lines += [
        "};",
        "",
        "// The nonterminals, sorted.",
        f"constexpr int kNonterminalCount = {len(nonterminals)};",
        "constexpr const char* kNonterminals[kNonterminalCount] = {",
    ]
    lines += [f'    "{n}",' for n in nonterminals]
    lines += [
        "};",
        "",
        f"constexpr int kStateCount = {states};",
        "",
        "// PLY's action of each state on each terminal: a state to shift to",
        "// when positive, the production to reduce by when negative (its",
        "// index negated), 0 to accept, and kNone for a syntax error.",
        "constexpr std::int16_t kAction[kStateCount][kTerminalCount] = {",
    ]
    for s in range(states):
        acts = p.action[s]
        cells = [str(acts[t]) if t in acts else "kNone" for t in terminals]
        lines.append("    {" + ", ".join(cells) + "},")
    lines += [
        "};",
        "",
        "// The state each state goes to after a reduction to each",
        "// nonterminal, or kNone.",
        "constexpr std::int16_t kGoto[kStateCount][kNonterminalCount] = {",
    ]
    for s in range(states):
        g = p.goto.get(s, {})
        cells = [str(g[n]) if n in g else "kNone" for n in nonterminals]
        lines.append("    {" + ", ".join(cells) + "},")
    lines += [
        "};",
        "",
        "// The reduction each state makes without reading a lookahead",
        "// (PLY's `defaulted_states`), or kNone.",
        "constexpr std::int16_t kDefaulted[kStateCount] = {",
    ]
    cells = [str(p.defaulted_states[s]) if s in p.defaulted_states
             else "kNone" for s in range(states)]
    for i in range(0, states, 12):
        lines.append("    " + ", ".join(cells[i:i + 12]) + ",")
    lines += [
        "};",
        "",
        "struct Production {",
        "  // The nonterminal the production reduces to.",
        "  const char* name;",
        "  // The number of symbols on its right-hand side.",
        "  int len;",
        "  // The name of the `p_` function of evaluator.py that is its",
        "  // action, or \"\" for the start production.",
        "  const char* func;",
        "};",
        "",
        "// The productions, by PLY's numbers, each with its rule.",
        f"constexpr int kProductionCount = {len(p.productions)};",
        "constexpr Production kProductions[kProductionCount] = {",
    ]
    for prod in p.productions:
        lines.append(f"    // {prod.str}")
        lines.append(f'    {{"{prod.name}", {prod.len}, '
                     f'"{prod.func or ""}"}},')
    ranges = _non_printable_ranges()
    lines += [
        "};",
        "",
        "// The ranges of code points, first and last, for which Python's",
        "// `str.isprintable` is false, in order, from the Unicode database",
        f"// of Python {sys.version_info.major}.{sys.version_info.minor} "
        f"(Unicode {unicodedata.unidata_version}).",
        f"constexpr int kNonPrintableCount = {len(ranges)};",
        "constexpr std::uint32_t kNonPrintable[kNonPrintableCount][2] = {",
    ]
    for i in range(0, len(ranges), 4):
        lines.append("    " + " ".join(
            f"{{0x{a:X}, 0x{b:X}}}," for a, b in ranges[i:i + 4]))
    lines += [
        "};",
        "",
        "}  // namespace c6502::pcpp::evaluator_tables",
        "",
    ]
    return "\n".join(lines)


def main() -> None:
    with open(_HEADER, "wb") as f:
        f.write(generate().encode("utf-8"))


if __name__ == "__main__":
    main()
