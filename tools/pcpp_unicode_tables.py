"""Writes cpp/src/pcpp_unicode.h, the classes of Unicode characters that
the C++ port of the preprocessor reads, from the Python that runs the
Python preprocessor.

pcpp's lexer compiles its rules as Python regular expressions on `str`,
where `\\w` and `\\d` match Unicode letters, digits, and the underscore,
and pcpp splits its input with `str.splitlines()` and strips each line
with `str.rstrip()`, which break and strip at Unicode line breaks and
spaces. preprocessor.py's pragma check splits with `str.split()`, and
Python's `repr` escapes the characters `str.isprintable()` rejects.
Each class here is the list of ranges of code points that Python
gives it, so the C++ answers as the Python that wrote the table does.

    uv run python tools/pcpp_unicode_tables.py

tests/test_pcpp_unicode_tables.py checks that the checked-in header is
what this writes.
"""

from __future__ import annotations

import os
import re
import sys
import unicodedata

_ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
_OUT = os.path.join(_ROOT, "cpp", "src", "pcpp_unicode.h")

# The code points that `str.splitlines()` breaks at, which the Python
# documentation lists (\r\n is one break).
_LINE_BREAKS = "\n\r\x0b\x0c\x1c\x1d\x1e\x85  "


def _ranges(test) -> list[tuple[int, int]]:
    """The ranges [first, last] of the code points for which `test`
    holds, in order."""
    out: list[tuple[int, int]] = []
    start = None
    for c in range(sys.maxunicode + 2):
        inside = c <= sys.maxunicode and test(chr(c))
        if inside and start is None:
            start = c
        elif not inside and start is not None:
            out.append((start, c - 1))
            start = None
    return out


def _table(name: str, ranges: list[tuple[int, int]]) -> str:
    rows = []
    line = "   "
    for a, b in ranges:
        item = f" {{0x{a:X}, 0x{b:X}}},"
        if len(line) + len(item) > 78:
            rows.append(line)
            line = "   "
        line += item
    rows.append(line)
    body = "\n".join(rows)
    return (
        f"inline constexpr Range {name}[] = {{\n{body}\n}};\n"
    )


def generate() -> str:
    word = re.compile(r"\w")
    digit = re.compile(r"\d")
    breaks = set(_LINE_BREAKS)
    assert all(len(("a" + ch + "b").splitlines()) == 2 for ch in breaks)
    parts = [
        "// Generated by tools/pcpp_unicode_tables.py from Python "
        f"{sys.version_info.major}.{sys.version_info.minor} (Unicode "
        f"{unicodedata.unidata_version}).\n"
        "// Don't edit it. Each table lists the ranges [first, last] of "
        "the code\n"
        "// points of one class, as Python gives the class.\n"
        "#pragma once\n\n"
        "#include <cstdint>\n\n"
        "namespace c6502::pcpp::unicode {\n\n"
        "struct Range {\n"
        "  std::uint32_t first;\n"
        "  std::uint32_t last;\n"
        "};\n\n",
        "// The characters `\\w` matches in a Python regular expression "
        "on a str.\n",
        _table("kWord", _ranges(lambda ch: word.match(ch) is not None)),
        "\n// The characters `\\d` matches.\n",
        _table("kDigit", _ranges(lambda ch: digit.match(ch) is not None)),
        "\n// The characters `str.isspace()` accepts, which `strip`, "
        "`rstrip`, and\n// `split` remove.\n",
        _table("kSpace", _ranges(str.isspace)),
        "\n// The characters `str.splitlines()` breaks at.\n",
        _table("kLineBreak", _ranges(lambda ch: ch in breaks)),
        "\n// The characters `str.isprintable()` accepts, which `repr` "
        "copies.\n",
        _table("kPrintable", _ranges(str.isprintable)),
        "\n}  // namespace c6502::pcpp::unicode\n",
    ]
    return "".join(parts)


def main() -> None:
    text = generate()
    with open(_OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    print(f"wrote {_OUT}")


if __name__ == "__main__":
    main()
